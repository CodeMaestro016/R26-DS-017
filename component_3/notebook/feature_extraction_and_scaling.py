def get_annotations_for(
    set_name,
    video
):

    key = (
        set_name,
        video
    )

    if key not in annotation_cache:

        ann_file = os.path.join(
            ANN_ROOT,
            set_name,
            video + "_annt.xml"
        )

        attr_file = os.path.join(
            ATTR_ROOT,
            set_name,
            video + "_attributes.xml"
        )

        if os.path.exists(ann_file):

            annotation_cache[key] = (
                load_annotations(
                    ann_file
                )
            )

        else:

            annotation_cache[key] = {}

        if os.path.exists(attr_file):

            attribute_cache[key] = (
                load_attributes(
                    attr_file
                )
            )

        else:

            attribute_cache[key] = {}

    return (
        annotation_cache[key],
        attribute_cache[key]
    )


