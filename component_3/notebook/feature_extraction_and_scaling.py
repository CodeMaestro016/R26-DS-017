def assign_frame_label(
    row,
    frame_attrs,
    track_attrs,
    frame
):

    if row is None:

        return -1

    if not np.all(
        np.isfinite(row)
    ):

        return -1

    if frame_attrs is None:

        return -1

    cross_raw = normalize_string(
        frame_attrs.get("cross")
    )

    crossing = CROSS_MAP.get(
        cross_raw,
        None
    )

    if crossing is None:

        return -1

    look = normalize_string(
        frame_attrs.get("look")
    )

    crosswalk_value = row[
        FEATURE_INDEX[
            "crosswalk_presence"
        ]
    ]

    if not np.isfinite(
        crosswalk_value
    ):

        return -1

    crosswalk_zero = np.isclose(
        crosswalk_value,
        0.0
    )

    vehicle_value = row[
        FEATURE_INDEX[
            "vehicle_distance"
        ]
    ]

    vehicle_nearby = (

        np.isfinite(
            vehicle_value
        )

        and

        vehicle_value
        < NO_VEHICLE_SENTINEL

        and

        vehicle_value
        <= vehicle_close_high
    )

    # -------------------------------------------------------------------------
    # JAYWALK
    # -------------------------------------------------------------------------

    if (
        crossing == 1
        and
        crosswalk_zero
    ):

        return 5

    if crossing == -1:

        return -1

    # -------------------------------------------------------------------------
