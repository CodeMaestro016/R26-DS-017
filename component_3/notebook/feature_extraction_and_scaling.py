def is_aggressive(
    current_speed_value,
    acceleration_value,
    deceleration_value,
    speed_variance_value
):

    high_variance = (

        np.isfinite(
            speed_variance_value
        )

        and

        speed_variance_value
        > speed_var_high
    )

    high_speed = (

        np.isfinite(
            current_speed_value
        )

        and

        current_speed_value
        > current_speed_high
    )

    strong_acceleration = (

        np.isfinite(
            acceleration_value
        )

        and

        acceleration_value
        > acceleration_high
    )

    strong_deceleration = (

        np.isfinite(
            deceleration_value
        )

        and

        deceleration_value
        > deceleration_high
    )

    distinct_signals = sum([
        high_speed,
        strong_acceleration,
        strong_deceleration
    ])

    if (
        high_variance
        and
        distinct_signals >= 2
    ):

        return True

    if (
        high_speed
        and
        (
            strong_acceleration
            or
            strong_deceleration
        )
    ):

        return True

    return False


