"""
One-off diagnostic: sweep random_state for the stratified track split and
report Hesitant (label 1) val/test sequence counts for each seed, so you
can pick a split where the scarce Hesitant data that DOES exist actually
lands somewhere you can evaluate it -- rather than being stuck with
whatever a single fixed seed happened to allocate.

This does NOT save any .npy files or touch the scaler -- it only counts
labels, using the exact same track-building / stratified-split /
windowing / contiguity logic as build_sequences_fixed.py, so the counts
it reports are what that script would actually produce for each seed.

Set SEQ_STEP below to whatever you're using for your real training run
(recommended: 5, not 1 -- see the note in build_sequences_fixed.py).
"""

import numpy as np
from collections import Counter, defaultdict
from sklearn.model_selection import train_test_split

PIE_PATH = "/content/drive/MyDrive/PIE"
FEATURE_PATH = f"{PIE_PATH}/processed_features_new"

SEQ_LEN = 30
SEQ_STEP = 5          # match your real training config, not the step=1 diagnostic
CANDIDATE_SEEDS = list(range(100))  # widened to 100 -- train coverage is rarer to hit than val/test

X_features = np.load(f"{FEATURE_PATH}/X_features.npy")
y_labels = np.load(f"{FEATURE_PATH}/y_labels.npy")
metadata = np.load(f"{FEATURE_PATH}/metadata.npy", allow_pickle=True)

mask = y_labels != -1
X_features, y_labels, metadata = X_features[mask], y_labels[mask], metadata[mask]

tracks = {}
for feat, label, meta in zip(X_features, y_labels, metadata):
    tid = (meta["set"], meta["video"], meta["pedestrian"])
    tracks.setdefault(tid, []).append((meta["frame"], feat, label, meta))
for tid in tracks:
    tracks[tid].sort(key=lambda x: x[0])

label_counts_global = Counter(int(l) for l in y_labels)
rarity_order = sorted(label_counts_global, key=lambda c: label_counts_global[c])

def track_priority_label(tid):
    labels_in_track = {int(x[2]) for x in tracks[tid]}
    for c in rarity_order:
        if c in labels_in_track:
            return c
    return 0

track_ids = list(tracks.keys())
priority = {tid: track_priority_label(tid) for tid in track_ids}
strat_labels = [priority[tid] for tid in track_ids]

def build_labels_only(track_list):
    """Same windowing + contiguity logic as build_sequences(), but skips
    feature scaling entirely -- we only need the resulting y values."""
    y = []
    for tid in track_list:
        track = tracks[tid]
        if len(track) < SEQ_LEN:
            continue
        for i in range(0, len(track) - SEQ_LEN + 1, SEQ_STEP):
            window = track[i:i + SEQ_LEN]
            frames = [x[0] for x in window]
            if max(np.diff(frames)) > 1:
                continue
            y.append(window[-1][2])
    return np.array(y)

print(f"{'seed':>5}  {'train_hesitant':>14}  {'val_hesitant':>12}  {'test_hesitant':>13}")
print("-" * 55)

best_seed, best_score = None, -1

for seed in CANDIDATE_SEEDS:
    train_tracks, temp_tracks = train_test_split(
        track_ids, test_size=0.30, random_state=seed, stratify=strat_labels
    )
    temp_strat = [priority[tid] for tid in temp_tracks]
    val_tracks, test_tracks = train_test_split(
        temp_tracks, test_size=0.50, random_state=seed, stratify=temp_strat
    )

    y_train = build_labels_only(train_tracks)
    y_val = build_labels_only(val_tracks)
    y_test = build_labels_only(test_tracks)

    train_h = int(np.sum(y_train == 1))
    val_h = int(np.sum(y_val == 1))
    test_h = int(np.sum(y_test == 1))
    print(f"{seed:>5}  {train_h:>14}  {val_h:>12}  {test_h:>13}")

    # train_h matters most (the model can't learn a pattern it never sees) --
    # heavily reward all-three-nonzero, then maximize train, then balance val/test
    all_nonzero = train_h > 0 and val_h > 0 and test_h > 0
    score = (100000 if all_nonzero else 0) + train_h * 10 + min(val_h, test_h)
    if score > best_score:
        best_score, best_seed = score, seed

print()
print(f"Best seed by train-first Hesitant coverage: {best_seed} "
      f"(use this as SPLIT_SEED in build_sequences_fixed.py)")

