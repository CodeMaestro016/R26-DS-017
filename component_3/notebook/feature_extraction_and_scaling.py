def is_hesitant_behavior(
    pause_duration_value,
    hesitation_cycles_value,
    direction_changes_value
):

    direct_evidence = (

        np.isfinite(
            hesitation_cycles_value
        )

        and

        hesitation_cycles_value >= 1
    )

    pause_high = (

        np.isfinite(
            pause_duration_value
        )

        and

        pause_duration_value
        > pause_duration_high
    )

    direction_high = (

        np.isfinite(
            direction_changes_value
        )

        and

        direction_changes_value
        > direction_changes_high
    )

    if direct_evidence:

        return True

    if (
        pause_high
        and
        direction_high
    ):

        return True

    return False


