def load_annotations(
    xml_file
):

    root = ET.parse(
        xml_file
    ).getroot()

    data = {}

    for track in root.findall(".//track"):

        if track.get("label") != "pedestrian":

            continue

        boxes = track.findall("box")

        if not boxes:

            continue

        first_attrs = {
            a.get("name"): a.text
            for a in boxes[0].findall("attribute")
        }

        pid = (
            first_attrs.get("id")
            or track.get("id")
        )

        if pid is None:

            continue

        data[pid] = {}

        for box in boxes:

            frame = int(
                box.get("frame")
            )

            attrs = {
                a.get("name"): a.text
                for a in box.findall("attribute")
            }

            data[pid][frame] = attrs

    return data


