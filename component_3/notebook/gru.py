# Generalized low-support signal diagnostic (Hesitant AND Aggressive, not
# just Hesitant) -- is there real signal even where argmax loses?
def print_signal_diagnostic(X, y, label, tag=''):
    probs = best_model.predict(X, verbose=0)
    mask = (y == label)
    if mask.sum() == 0:
        print(f'  [{tag}] no examples of {LABEL_NAMES[label]} in this set -- skip')
        return
    p_true = probs[mask, label].mean()
    p_other = probs[~mask, label].mean()
    print(f'  [{tag}] {LABEL_NAMES[label]:<12} mean P(class) on true examples: {p_true:.4f}  |  '
          f'on everything else: {p_other:.4f}  |  gap: {p_true - p_other:+.4f}')

