def build_gru_model(seq_len=30, n_features=36, n_classes=6):
    """
    Two-layer GRU for pedestrian mental state classification.
    Same shape/regularization as the LSTM version -- the imbalance
    problem was in training/evaluation, not model capacity, so there's
    no reason to change layer sizes or dropout when swapping cell type.
    """
    inputs = keras.Input(shape=(seq_len, n_features), name='sequence_input')

    x = layers.GRU(
        128, return_sequences=True,
        kernel_regularizer=keras.regularizers.l2(1e-4),
        name='gru_1'
    )(inputs)
    x = layers.Dropout(0.3, name='dropout_1')(x)

    x = layers.GRU(
        64, return_sequences=False,
        kernel_regularizer=keras.regularizers.l2(1e-4),
        name='gru_2'
    )(x)
    x = layers.Dropout(0.3, name='dropout_2')(x)

    outputs = layers.Dense(n_classes, activation='softmax', name='mental_state_output')(x)

    return keras.Model(inputs=inputs, outputs=outputs, name='GRU_MentalState')


