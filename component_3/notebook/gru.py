# ============================================================
# 4. SMOOTHED MACRO-F1 CHECKPOINT
#    Checkpoints/stops on a moving average of val macro F1, not val_loss
#    (val_loss previously picked an underfit early-epoch model) and not
#    the raw per-epoch macro F1 either (too noisy given 3-7 example
#    classes).
# ============================================================

class SmoothedMacroF1Checkpoint(callbacks.Callback):
    def __init__(self, X_val, y_val, save_path, patience=15, window=3, label_names=None):
        super().__init__()
        self.X_val, self.y_val = X_val, y_val
        self.save_path = save_path
        self.patience = patience
        self.history = deque(maxlen=window)
        self.best_smoothed = -1.0
        self.best_epoch = -1
        self.best_raw_f1 = -1.0
        self.wait = 0
        self.label_names = label_names or [str(i) for i in range(N_CLASSES)]

    def on_epoch_end(self, epoch, logs=None):
        probs = self.model.predict(self.X_val, verbose=0)
        preds = np.argmax(probs, axis=1)
        raw_f1 = f1_score(self.y_val, preds, average='macro', zero_division=0)

        self.history.append(raw_f1)
        smoothed = sum(self.history) / len(self.history)

        print(f'  val_macro_f1={raw_f1:.4f}  smoothed(last {len(self.history)})={smoothed:.4f}'
              f'  (best smoothed so far: {self.best_smoothed:.4f} @ epoch {self.best_epoch})')

        if smoothed > self.best_smoothed:
            self.best_smoothed = smoothed
            self.best_raw_f1 = raw_f1
            self.best_epoch = epoch + 1
            self.wait = 0
            self.model.save(self.save_path)
            print('  -> new best smoothed val macro F1, checkpoint saved.')
        else:
            self.wait += 1
            if self.wait >= self.patience:
                print(f'  -> no improvement in {self.patience} epochs, stopping.')
                self.model.stop_training = True


