# 2. EFFECTIVE-NUMBER-OF-SAMPLES CLASS WEIGHTS
#    Cui et al., "Class-Balanced Loss Based on Effective Number of
#    Samples", CVPR 2019.
# ============================================================

def effective_number_weights(y, n_classes, beta=EFFECTIVE_NUM_BETA):
    counts = {c: int(np.sum(y == c)) for c in range(n_classes)}
    weights = {}
    for c, n in counts.items():
        n = max(n, 1)  # guard against a class with zero examples
        eff_num = (1 - beta**n) / (1 - beta)
        weights[c] = 1.0 / eff_num
    mean_w = sum(weights.values()) / len(weights)
    return {c: w / mean_w for c, w in weights.items()}, counts


class_weights, train_counts = effective_number_weights(y_train, N_CLASSES)

