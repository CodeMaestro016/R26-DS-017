def process_video(xml_file, video_file, save_folder):


    print("\n================================")
    print(video_file.name)


    save_folder.mkdir(
        parents=True,
        exist_ok=True
    )

    # ==================================
    # CACHE EXISTING LANDMARK FILES
    # ==================================

    existing_files = {
        f.name for f in save_folder.glob("*.npy")
    }

    print("Existing landmark files:", len(existing_files))

    # -------------------------
    # READ XML
    # -------------------------

    tree = ET.parse(xml_file)

    root = tree.getroot()



    frame_data = {}



    for track in root.findall(".//track"):


        if track.attrib.get("label") != "pedestrian":

            continue



        for box in track.findall("box"):



            frame_id = int(
                box.attrib["frame"]
            )



            # =========================
            # GET PIE PED ID
            # =========================


            ped_id = "unknown"



            for attr in box.findall("attribute"):


                if attr.attrib.get("name") == "id":


                    ped_id = attr.text

                    break




            # =========================
            # BOUNDING BOX
            # =========================


            xmin = int(float(box.attrib["xtl"]))
            ymin = int(float(box.attrib["ytl"]))
            xmax = int(float(box.attrib["xbr"]))
            ymax = int(float(box.attrib["ybr"]))



            frame_data.setdefault(
                frame_id,
                []
            )


            frame_data[frame_id].append(

                {

                "ped_id":ped_id,

                "bbox":
                    (
                    xmin,
                    ymin,
                    xmax,
                    ymax
                    )

                }

            )



    print(
        "Annotated frames:",
        len(frame_data)
    )

    # ==================================
    # CHECK IF VIDEO IS ALREADY COMPLETE
    # ==================================

    expected_files = sum(
        len(persons)
        for persons in frame_data.values()
    )

    if len(existing_files) >= expected_files:

        print("Video already processed.")
        return

    # -------------------------
    # VIDEO
    # -------------------------

    cap = cv2.VideoCapture(
        str(video_file)
    )



    saved = 0

    skipped = 0

    failed = 0



    # ==================================
    # SORT FRAME IDS FOR SEQUENTIAL READ
    # ==================================
    # Seeking with CAP_PROP_POS_FRAMES on every frame is slow because
    # most codecs must decode forward from the nearest keyframe.
    # Instead we walk through the video sequentially once, using the
    # cheap cap.grab() to skip frames we don't need and cap.read()
    # only on frames we actually have to decode.

    frame_ids_sorted = sorted(frame_data.keys())

    current_frame = 0

    cap.set(cv2.CAP_PROP_POS_FRAMES, 0)


    for frame_id in frame_ids_sorted:

        persons = frame_data[frame_id]

        # ==========================
        # CHECK CACHE FIRST
        # (no seeking/decoding at all if nothing is missing)
        # ==========================

        need_frame = False

        for person in persons:

            filename = (
                f"frame_{frame_id:06d}"
                f"_ped_{person['ped_id']}.npy"
            )

            if filename not in existing_files:
                need_frame = True
                break

        if not need_frame:

            skipped += len(persons)
            continue


        # ==========================
        # ADVANCE SEQUENTIALLY TO frame_id
        # ==========================

        # if for some reason frame_id is behind current_frame
        # (out-of-order XML data), fall back to a direct seek
        if frame_id < current_frame:

            cap.set(cv2.CAP_PROP_POS_FRAMES, frame_id)
            current_frame = frame_id

        else:

            while current_frame < frame_id:

                cap.grab()   # cheap skip, no full decode/copy
                current_frame += 1


        ret, frame = cap.read()
        current_frame += 1

        if not ret:

            continue


        h,w,_ = frame.shape


        for person in persons:



            ped_id = person["ped_id"]



            filename = (

                f"frame_{frame_id:06d}"
                f"_ped_{ped_id}.npy"

            )



            save_file = (

                save_folder /
                filename

            )



            # ==========================
            # RESUME FEATURE
            # ==========================

            if filename in existing_files:

                skipped += 1

                continue



            xmin,ymin,xmax,ymax = person["bbox"]



            xmin=max(0,xmin)

            ymin=max(0,ymin)

            xmax=min(w,xmax)

            ymax=min(h,ymax)



            crop = frame[

                ymin:ymax,

                xmin:xmax

            ]



            if crop.size == 0:

                continue



            # BGR -> RGB

            crop=cv2.cvtColor(

                crop,

                cv2.COLOR_BGR2RGB

            )



            mp_image = mp.Image(

                image_format =
                mp.ImageFormat.SRGB,

                data=crop

            )



            result = detector.detect(
                mp_image
            )



            if result.pose_landmarks:



                landmarks=[]



                for lm in result.pose_landmarks[0]:


                    landmarks.extend(

                        [

                        lm.x,

                        lm.y,

                        lm.z,

                        lm.visibility

                        ]

                    )



                landmarks=np.array(

                    landmarks,

                    dtype=np.float32

                )



                np.save(
                      save_file,
                      landmarks
                  )

                existing_files.add(filename)

                saved += 1



            else:

                failed += 1



    cap.release()



    print(
        "Saved landmarks:",
        saved
    )


    print(
        "Skipped existing:",
        skipped
    )


    print(
        "Pose failed:",
        failed
    )





