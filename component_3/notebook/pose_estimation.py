import pandas as pd
from pathlib import Path

PIE_PATH = "/content/drive/MyDrive/PIE"

LANDMARK_ROOT = Path(PIE_PATH) / "pose_landmarks"
ANNOTATION_ROOT = Path(PIE_PATH) / "annotations"

print("="*70)
print("VERIFYING LANDMARK DATASET")
print("="*70)

report = []

total_landmarks = 0
completed_videos = 0
missing_videos = 0

xml_files = sorted(ANNOTATION_ROOT.rglob("*.xml"))

print("Expected videos:", len(xml_files))
print()

for xml in xml_files:

    set_name = xml.parent.name

    video_name = xml.stem.replace("_annt", "")

    landmark_folder = LANDMARK_ROOT / set_name / video_name

    exists = landmark_folder.exists()

    if not exists:

        report.append({
            "set": set_name,
            "video": video_name,
            "status": "MISSING",
            "landmarks": 0
        })

        missing_videos += 1
        continue

    npy_files = list(landmark_folder.glob("*.npy"))

    landmark_count = len(npy_files)

    total_landmarks += landmark_count

    complete = (landmark_folder / "COMPLETE.txt").exists()

    if complete:
        completed_videos += 1

    if landmark_count == 0:
        status = "EMPTY"
    elif complete:
        status = "COMPLETE"
    else:
        status = "PARTIAL"

    report.append({
        "set": set_name,
        "video": video_name,
        "status": status,
        "landmarks": landmark_count
    })

df = pd.DataFrame(report)

print("="*70)
print("SUMMARY")
print("="*70)

print("Total XML videos           :", len(xml_files))
print("Completed videos           :", completed_videos)
print("Missing videos             :", missing_videos)
print("Total landmark files       :", total_landmarks)

print()

print("="*70)
print("PER SET SUMMARY")
print("="*70)

summary = df.groupby("set").agg(
    videos=("video","count"),
    completed=("status", lambda x:(x=="COMPLETE").sum()),
    partial=("status", lambda x:(x=="PARTIAL").sum()),
    empty=("status", lambda x:(x=="EMPTY").sum()),
    missing=("status", lambda x:(x=="MISSING").sum()),
    landmarks=("landmarks","sum")
)

print(summary)

print()

print("="*70)
print("VIDEOS REQUIRING ATTENTION")
print("="*70)

problem = df[df.status != "COMPLETE"]

if len(problem)==0:
    print("All videos completed.")
else:
    print(problem)

csv_path = LANDMARK_ROOT / "landmark_verification_report.csv"

df.to_csv(csv_path,index=False)

print()
print("Report saved to:")
print(csv_path)
