def parse_annotation_xml(xml_path):

    frame_data = defaultdict(
        lambda: {
            "pedestrians": [],
            "traffic_lights": [],
            "crosswalks": [],
            "vehicles": []
        }
    )

    root = ET.parse(xml_path).getroot()

    for track in root.findall("track"):

        label = track.attrib.get(
            "label",
            ""
        )

        for box in track.findall("box"):

            if box.attrib.get("outside", "0") == "1":
                continue

            frame_id = int(
                box.attrib["frame"]
            )

            bbox = [
                float(box.attrib["xtl"]),
                float(box.attrib["ytl"]),
                float(box.attrib["xbr"]),
                float(box.attrib["ybr"])
            ]

            attrs = {}

            for attribute in box.findall("attribute"):

                name = attribute.attrib["name"]

                value = (
                    attribute.text.strip()
                    if attribute.text
                    else ""
                )

                attrs[name] = value


            # ----------------------------------------------------
            # PEDESTRIAN
            # ----------------------------------------------------

            if label == "pedestrian":

                frame_data[frame_id][
                    "pedestrians"
                ].append({

                    "id": attrs.get(
                        "id",
                        ""
                    ),

                    "bbox": bbox,

                    "action": attrs.get(
                        "action",
                        "standing"
                    ),

                    "cross": attrs.get(
                        "cross",
                        "not-crossing"
                    ),

                    "look": attrs.get(
                        "look",
                        "not-looking"
                    ),

                    "gesture": attrs.get(
                        "gesture",
                        "__undefined__"
                    )
                })


            # ----------------------------------------------------
            # VEHICLE
            # ----------------------------------------------------

            elif label == "vehicle":

                frame_data[frame_id][
                    "vehicles"
                ].append({

                    "bbox": bbox,

                    "type": attrs.get(
                        "type",
                        "car"
                    )
                })


            # ----------------------------------------------------
            # TRAFFIC LIGHT
            # ----------------------------------------------------

            elif label == "traffic_light":

                frame_data[frame_id][
                    "traffic_lights"
                ].append({

                    "bbox": bbox,

                    "state": attrs.get(
                        "state",
                        "none"
                    )
                })


            # ----------------------------------------------------
            # CROSSWALK
            # ----------------------------------------------------

            elif label == "crosswalk":

                frame_data[frame_id][
                    "crosswalks"
                ].append({

                    "bbox": bbox
                })

    return frame_data


