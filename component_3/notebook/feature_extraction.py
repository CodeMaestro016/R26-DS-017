# DISTANCE TO CURB PROXY
# ================================================================

def compute_distance_to_curb(
    ped_bbox,
    frame_info
):
    """
    PIE does not provide an explicit curb annotation.

    Scientifically safer proxy:
    distance from pedestrian center to the nearest
    annotated crosswalk region/boundary.

    Returns normalized image distance.
    """

    crosswalks = frame_info.get(
        "crosswalks",
        []
    )

    if not crosswalks:
        return 1.0


    ped_center = bbox_center(
        ped_bbox
    )


    distances = [

        point_to_bbox_distance(
            ped_center,
            crosswalk["bbox"]
        )

        for crosswalk in crosswalks
    ]


    nearest_distance = min(
        distances
    )


    normalized_distance = (
        nearest_distance
        /
        IMAGE_DIAGONAL
    )


    return float(
        np.clip(
            normalized_distance,
            0.0,
            1.0
        )
    )


