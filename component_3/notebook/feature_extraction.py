def bbox_center(bbox):

    x1, y1, x2, y2 = bbox

    return (
        (x1 + x2) / 2.0,
        (y1 + y2) / 2.0
    )


def bbox_iou(b1, b2):

    ix1 = max(b1[0], b2[0])
    iy1 = max(b1[1], b2[1])

    ix2 = min(b1[2], b2[2])
    iy2 = min(b1[3], b2[3])

    inter_width = max(0.0, ix2 - ix1)
    inter_height = max(0.0, iy2 - iy1)

    intersection = inter_width * inter_height

    if intersection <= 0:
        return 0.0

    area1 = (
        (b1[2] - b1[0])
        *
        (b1[3] - b1[1])
    )

    area2 = (
        (b2[2] - b2[0])
        *
        (b2[3] - b2[1])
    )

    union = area1 + area2 - intersection

    if union <= 0:
        return 0.0

    return intersection / union


def point_to_bbox_distance(point, bbox):
    """
    Euclidean distance from a point to the nearest point
    of a bounding box.
    """

    x, y = point

    x1, y1, x2, y2 = bbox

    dx = max(
        x1 - x,
        0.0,
        x - x2
    )

    dy = max(
        y1 - y,
        0.0,
        y - y2
    )

    return float(
        math.hypot(dx, dy)
    )


