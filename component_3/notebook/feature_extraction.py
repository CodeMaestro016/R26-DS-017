# ================================================================

def compute_motion_features(
    track,
    landmarks=None
):

    hip_positions = []

    left_ankles = []

    right_ankles = []

    frames = []


    for idx, item in enumerate(track):

        lm = (
            landmarks[idx]
            if landmarks is not None
            else load_landmarks(
                item["file"]
            )
        )

        hip = midpoint(
            lm[L_HIP],
            lm[R_HIP]
        )

        hip_positions.append(
            hip[:2]
        )

        left_ankles.append(
            lm[L_ANKLE][:2]
        )

        right_ankles.append(
            lm[R_ANKLE][:2]
        )

        frames.append(
            item["frame"]
        )


    speeds = []

    for i in range(
        1,
        len(hip_positions)
    ):

        gap = (
            frames[i]
            -
            frames[i - 1]
        )

        if gap <= 0:
            continue

        distance = np.linalg.norm(
            np.array(hip_positions[i])
            -
            np.array(hip_positions[i - 1])
        )

        speeds.append(
            distance / gap
        )


    speeds = np.array(
        speeds
        if speeds
        else [0.0]
    )


    features = np.zeros(
        10,
        dtype=np.float32
    )


    # 1 current_speed

    features[0] = speeds[-1]


    # 2 avg_speed

    features[1] = np.mean(
        speeds
    )


    # 3 max_speed

    features[2] = np.max(
        speeds
    )


    # 4 acceleration

    if len(speeds) > 1:

        acceleration_values = np.diff(
            speeds
        )

        positive = acceleration_values[
            acceleration_values > 0
        ]

        features[3] = (
            np.mean(positive)
            if len(positive) > 0
            else 0.0
        )


    # 5 deceleration

    if len(speeds) > 1:

        acceleration_values = np.diff(
            speeds
        )

        negative = acceleration_values[
            acceleration_values < 0
        ]

        features[4] = (
            abs(np.mean(negative))
            if len(negative) > 0
            else 0.0
        )


    # 6 speed_variance

    features[5] = np.var(
        speeds
    )


    # 7 step_frequency

    features[6] = np.mean(
        speeds >= SPEED_THRESHOLD
    )


    # 8 left_step_length

    if len(left_ankles) > 1:

        left_displacements = [

            np.linalg.norm(
                np.array(
                    left_ankles[i]
                )
                -
                np.array(
                    left_ankles[i - 1]
                )
            )

            for i in range(
                1,
                len(left_ankles)
            )
        ]

        features[7] = np.mean(
            left_displacements
        )


    # 9 right_step_length

    if len(right_ankles) > 1:

        right_displacements = [

            np.linalg.norm(
                np.array(
                    right_ankles[i]
                )
                -
                np.array(
                    right_ankles[i - 1]
                )
            )

            for i in range(
                1,
                len(right_ankles)
            )
        ]

        features[8] = np.mean(
            right_displacements
        )


    # 10 pause_between_steps

    features[9] = np.mean(
        speeds < SPEED_THRESHOLD
    )


    return features


