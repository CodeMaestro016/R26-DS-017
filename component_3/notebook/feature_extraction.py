# BEHAVIOUR FEATURES (9)
# ================================================================

def compute_behavior_features(
    track,
    frame_data,
    ped_id,
    landmarks=None
):

    features = np.zeros(
        9,
        dtype=np.float32
    )


    speeds = []

    frames = []

    positions = []

    left_look_flags = []

    right_look_flags = []

    current_ped_bbox = None

    current_frame_info = None


    # ------------------------------------------------------------
    # Collect trajectory and look information
    # ------------------------------------------------------------

    for idx, item in enumerate(track):

        frame_id = item["frame"]


        lm = (
            landmarks[idx]
            if landmarks is not None
            else load_landmarks(
                item["file"]
            )
        )


        hip = midpoint(
            lm[L_HIP],
            lm[R_HIP]
        )


        positions.append(
            hip[:2]
        )

        frames.append(
            frame_id
        )


        ped_info = get_ped_info(
            frame_data,
            frame_id,
            ped_id
        )


        if ped_info is not None:

            current_ped_bbox = ped_info["bbox"]

            current_frame_info = frame_data[
                frame_id
            ]


            # Only estimate left/right when PIE confirms
            # that the pedestrian is actually looking.

            if (
                ped_info.get("look")
                ==
                "looking"
            ):

                direction = estimate_head_direction(
                    lm
                )


                if direction == -1:

                    left_look_flags.append(
                        1.0
                    )

                    right_look_flags.append(
                        0.0
                    )


                elif direction == 1:

                    left_look_flags.append(
                        0.0
                    )

                    right_look_flags.append(
                        1.0
                    )


    # ------------------------------------------------------------
    # Calculate speed
    # ------------------------------------------------------------

    for i in range(
        1,
        len(positions)
    ):

        gap = (
            frames[i]
            -
            frames[i - 1]
        )


        if gap <= 0:
            continue


        distance = np.linalg.norm(
            np.array(
                positions[i]
            )
            -
            np.array(
                positions[i - 1]
            )
        )


        speeds.append(
            distance / gap
        )


    speeds = np.array(
        speeds
        if speeds
        else [0.0]
    )


    paused = (
        speeds
        <
        SPEED_THRESHOLD
    )


    moving = (
        speeds
        >=
        SPEED_THRESHOLD
    )


    # ------------------------------------------------------------
    # 23 pause_duration
    #
    # Average duration of a continuous pause run.
    # ------------------------------------------------------------

    pause_run_lengths = []

    current_run = 0


    for is_paused in paused:

        if is_paused:

            current_run += 1

        else:

            if current_run > 0:

                pause_run_lengths.append(
                    current_run
                )

            current_run = 0


    if current_run > 0:

        pause_run_lengths.append(
            current_run
        )


    if pause_run_lengths:

        features[0] = (
            np.mean(
                pause_run_lengths
            )
            /
            max(
                len(speeds),
                1
            )
        )


    # ------------------------------------------------------------
    # 24 hesitation_cycles
    #
    # Number of moving/stopped state transitions,
    # normalized to avoid track/window-length bias.
    # ------------------------------------------------------------

    if len(moving) > 1:

        transitions = sum(

            moving[i]
            !=
            moving[i - 1]

            for i in range(
                1,
                len(moving)
            )
        )


        features[1] = (

            transitions
            /
            (
                len(moving)
                -
                1
            )
        )


    # ------------------------------------------------------------
    # 25 total_hesitation_time
    #
    # Counts pauses that begin AFTER movement.
    # Excludes continuously standing pedestrians.
    # ------------------------------------------------------------

    hesitation_frames = 0

    i = 1


    while i < len(moving):

        if (

            moving[i - 1]

            and

            not moving[i]
        ):

            j = i


            while (

                j < len(moving)

                and

                not moving[j]
            ):

                hesitation_frames += 1

                j += 1


            i = j

        else:

            i += 1


    features[2] = (

        hesitation_frames
        /
        max(
            len(speeds),
            1
        )
    )


    # ------------------------------------------------------------
    # 26 distance_to_curb
    #
    # Crosswalk-boundary proximity proxy.
    # ------------------------------------------------------------

    if (

        current_ped_bbox is not None

        and

        current_frame_info is not None
    ):

        features[3] = compute_distance_to_curb(

            current_ped_bbox,

            current_frame_info
        )

    else:

        features[3] = 1.0


    # ------------------------------------------------------------
    # 27 distance_change_rate
    #
    # Average frame-to-frame path displacement.
    # ------------------------------------------------------------

    if len(positions) > 1:

        path_distance = sum(

            np.linalg.norm(

                np.array(
                    positions[i]
                )

                -

                np.array(
                    positions[i - 1]
                )
            )

            for i in range(
                1,
                len(positions)
            )
        )


        total_frame_span = max(

            frames[-1]
            -
            frames[0],

            1
        )


        features[4] = (

            path_distance
            /
            total_frame_span
        )


    # ------------------------------------------------------------
    # 28 temporal_movement_probability
    #
    # Recent frames have greater weight.
    # ------------------------------------------------------------

    if len(speeds) > 0:

        weights = np.exp(

            np.linspace(
                -1.0,
                0.0,
                len(speeds)
            )
        )


        weights = (
            weights
            /
            weights.sum()
        )


        features[5] = float(

            np.sum(

                weights

                *

                moving.astype(
                    float
                )
            )
        )


    # ------------------------------------------------------------
    # 29 looks_left
    #
    # Image-left head direction among PIE-confirmed
    # looking frames.
    # ------------------------------------------------------------

    if left_look_flags:

        features[6] = float(

            np.mean(
                left_look_flags
            )
        )

    else:

        features[6] = 0.0


    # ------------------------------------------------------------
    # 30 looks_right
    #
    # Image-right head direction among PIE-confirmed
    # looking frames.
    # ------------------------------------------------------------

    if right_look_flags:

        features[7] = float(

            np.mean(
                right_look_flags
            )
        )

    else:

        features[7] = 0.0


    # ------------------------------------------------------------
    # 31 direction_changes
    #
    # True 2D trajectory direction changes.
    # ------------------------------------------------------------

    if len(positions) > 2:

        displacement_vectors = np.diff(

            np.array(
                positions
            ),

            axis=0
        )


        directions = np.degrees(

            np.arctan2(

                displacement_vectors[:, 1],

                displacement_vectors[:, 0]
            )
        )


        changes = 0

        valid_pairs = 0


        for i in range(
            1,
            len(directions)
        ):

            previous_vector = (
                displacement_vectors[
                    i - 1
                ]
            )

            current_vector = (
                displacement_vectors[
                    i
                ]
            )


            if (

                np.linalg.norm(
                    previous_vector
                )
                <
                1e-6

                or

                np.linalg.norm(
                    current_vector
                )
                <
                1e-6
            ):

                continue


            valid_pairs += 1


            difference = angular_difference(

                directions[i - 1],

                directions[i]
            )


            if (

                difference
                >
                DIRECTION_CHANGE_THRESHOLD_DEGREES
            ):

                changes += 1


        features[8] = (

            changes
            /
            max(
                valid_pairs,
                1
            )
        )


    return features


