def parse_ped_attributes(xml_path):

    ped_attributes = {}

    root = ET.parse(xml_path).getroot()

    for ped in root.findall("pedestrian"):

        ped_id = ped.attrib.get(
            "id",
            ""
        )

        if not ped_id:
            continue

        def safe_float(value, default=0.0):

            try:
                return float(value)
            except:
                return default


        ped_attributes[ped_id] = {

            "age": ped.attrib.get(
                "age",
                "unknown"
            ),

            "gender": ped.attrib.get(
                "gender",
                "unknown"
            ),

            "crossing": ped.attrib.get(
                "crossing",
                ""
            ),

            "crossing_point": safe_float(
                ped.attrib.get(
                    "crossing_point",
                    0
                )
            ),

            "critical_point": safe_float(
                ped.attrib.get(
                    "critical_point",
                    0
                )
            ),

            "exp_start_point": safe_float(
                ped.attrib.get(
                    "exp_start_point",
                    0
                )
            ),

            "intention_prob": safe_float(
                ped.attrib.get(
                    "intention_prob",
                    0
                )
            ),

            "intersection": ped.attrib.get(
                "intersection",
                "unknown"
            ),

            "num_lanes": safe_float(
                ped.attrib.get(
                    "num_lanes",
                    0
                )
            ),

            "signalized": ped.attrib.get(
                "signalized",
                "n/a"
            ),

            "traffic_direction": ped.attrib.get(
                "traffic_direction",
                "unknown"
            )
        }

    return ped_attributes


