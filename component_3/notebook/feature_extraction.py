def estimate_head_direction(lm):
    """
    Returns:

    -1 : looking toward image-left
     0 : frontal / uncertain
     1 : looking toward image-right

    Uses nose displacement relative to the midpoint
    between the ears.

    This is an image-coordinate head-direction proxy.
    """

    nose = np.array(
        lm[NOSE][:2]
    )

    left_ear = np.array(
        lm[L_EAR][:2]
    )

    right_ear = np.array(
        lm[R_EAR][:2]
    )

    ear_mid = midpoint(
        left_ear,
        right_ear
    )

    head_width = np.linalg.norm(
        right_ear - left_ear
    )

    if head_width < 1e-6:
        return 0

    normalized_offset = (
        (nose[0] - ear_mid[0])
        /
        head_width
    )

    if normalized_offset < -HEAD_DIRECTION_THRESHOLD:
        return -1

    if normalized_offset > HEAD_DIRECTION_THRESHOLD:
        return 1

    return 0


