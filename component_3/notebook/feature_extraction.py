def compute_context_features(
    frame_info,
    ped_id,
    ped_bbox,
    ped_attributes
):

    features = []


    ped_center = bbox_center(
        ped_bbox
    )


    # ------------------------------------------------------------
    # 32 traffic_light_state
    #
    # Use nearest traffic light rather than arbitrary first light.
    # ------------------------------------------------------------

    lights = frame_info.get(
        "traffic_lights",
        []
    )


    if lights:

        nearest_light = min(

            lights,

            key=lambda light:

                math.hypot(

                    bbox_center(
                        light["bbox"]
                    )[0]

                    -

                    ped_center[0],

                    bbox_center(
                        light["bbox"]
                    )[1]

                    -

                    ped_center[1]
                )
        )


        traffic_light = TL_MAP.get(

            nearest_light.get(
                "state",
                "none"
            ),

            -1.0
        )

    else:

        traffic_light = -1.0


    features.append(
        traffic_light
    )


    # ------------------------------------------------------------
    # 33 vehicle_distance
    #
    # Nearest vehicle center distance.
    # Normalized by image diagonal.
    # ------------------------------------------------------------

    vehicles = frame_info.get(
        "vehicles",
        []
    )


    if not vehicles:

        vehicle_distance = 1.0

    else:

        distances = []

        for vehicle in vehicles:

            vehicle_center = bbox_center(
                vehicle["bbox"]
            )


            distance = math.hypot(

                vehicle_center[0]
                -
                ped_center[0],

                vehicle_center[1]
                -
                ped_center[1]
            )


            distances.append(
                distance
            )


        vehicle_distance = (

            min(distances)
            /
            IMAGE_DIAGONAL
        )


    features.append(

        float(

            np.clip(

                vehicle_distance,

                0.0,

                1.0
            )
        )
    )


    # ------------------------------------------------------------
    # 34 crosswalk_presence
    #
    # True if pedestrian overlaps an annotated crosswalk.
    # ------------------------------------------------------------

    crosswalks = frame_info.get(
        "crosswalks",
        []
    )


    crosswalk_presence = 0.0


    for crosswalk in crosswalks:

        if bbox_iou(

            ped_bbox,

            crosswalk["bbox"]
        ) > 0.0:

            crosswalk_presence = 1.0

            break


    features.append(
        crosswalk_presence
    )


    # ------------------------------------------------------------
    # 35 road_width
    #
    # Uses num_lanes from ped_attributes.
    # ------------------------------------------------------------

    ped_info = ped_attributes.get(

        ped_id,

        {}
    )


    num_lanes = float(

        ped_info.get(
            "num_lanes",
            0.0
        )
    )


    road_width = (

        num_lanes
        /
        MAX_LANES
    )


    features.append(

        float(

            np.clip(

                road_width,

                0.0,

                1.0
            )
        )
    )


    # ------------------------------------------------------------
    # 36 pedestrian_density
    #
    # Number of other pedestrians in the frame.
    # ------------------------------------------------------------

    pedestrians = frame_info.get(
        "pedestrians",
        []
    )


    other_pedestrians = [

        pedestrian

        for pedestrian in pedestrians

        if pedestrian.get("id") != ped_id
    ]


    density = (

        len(
            other_pedestrians
        )

        /

        10.0
    )


    features.append(

        float(

            np.clip(

                density,

                0.0,

                1.0
            )
        )
    )


    return np.array(

        features,

        dtype=np.float32
    )


