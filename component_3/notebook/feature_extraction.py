# POSE FEATURES (12)
# ================================================================

def compute_pose_features(
    track,
    landmarks=None
):

    lm = (
        landmarks[-1]
        if landmarks is not None
        else load_landmarks(
            track[-1]["file"]
        )
    )


    ls = lm[L_SHOULDER]

    rs = lm[R_SHOULDER]

    lh = lm[L_HIP]

    rh = lm[R_HIP]

    la = lm[L_ANKLE]

    ra = lm[R_ANKLE]

    lf = lm[L_FOOT_INDEX]

    rf = lm[R_FOOT_INDEX]

    nose = lm[NOSE]


    shoulder_mid = midpoint(
        ls,
        rs
    )

    hip_mid = midpoint(
        lh,
        rh
    )


    features = np.zeros(
        12,
        dtype=np.float32
    )


    # 11 upper_body_angle

    features[0] = vertical_angle(
        hip_mid,
        shoulder_mid
    )


    # 12 lower_body_angle

    knee_mid = midpoint(
        lm[L_KNEE],
        lm[R_KNEE]
    )

    features[1] = vertical_angle(
        hip_mid,
        knee_mid
    )


    # 13 head_angle

    features[2] = vertical_angle(
        shoulder_mid,
        nose
    )


    # 14 head_turn_frequency

    head_directions = []

    for lm_t in landmarks:

        head_directions.append(
            estimate_head_direction(
                lm_t
            )
        )

    turns = 0

    previous_direction = 0

    for direction in head_directions:

        if direction == 0:
            continue

        if (
            previous_direction != 0
            and direction != previous_direction
        ):
            turns += 1

        previous_direction = direction


    features[3] = (
        turns
        /
        max(
            len(landmarks) - 1,
            1
        )
    )


    # 15 shoulder_angle

    features[4] = horizontal_angle(
        ls,
        rs
    )


    # 16 hip_angle

    features[5] = horizontal_angle(
        lh,
        rh
    )


    # 17 foot_angle_left

    features[6] = angle_between(
        lh,
        la,
        lf
    )


    # 18 foot_angle_right

    features[7] = angle_between(
        rh,
        ra,
        rf
    )


    # 19 forward_lean

    features[8] = abs(
        shoulder_mid[1]
        -
        hip_mid[1]
    )


    # 20 lateral_lean

    features[9] = abs(
        shoulder_mid[0]
        -
        hip_mid[0]
    )


    # 21 body_orientation
    #
    # Horizontal torso-axis orientation.

    features[10] = horizontal_angle(
        hip_mid,
        shoulder_mid
    )


    # 22 body_orientation_change
    #
    # IMPORTANT:
    # Uses the SAME torso-axis definition as body_orientation.

    orientations = []

    for lm_t in landmarks:

        shoulder_mid_t = midpoint(
            lm_t[L_SHOULDER],
            lm_t[R_SHOULDER]
        )

        hip_mid_t = midpoint(
            lm_t[L_HIP],
            lm_t[R_HIP]
        )

        orientation = horizontal_angle(
            hip_mid_t,
            shoulder_mid_t
        )

        orientations.append(
            orientation
        )


    if len(orientations) > 1:

        changes = [

            angular_difference(
                orientations[i - 1],
                orientations[i]
            )

            for i in range(
                1,
                len(orientations)
            )
        ]

        features[11] = np.mean(
            changes
        )


    return features


